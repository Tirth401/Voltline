/**
 * Generates TypeScript types for every OCPP 1.6 payload straight from the official schemas, so the
 * types can never drift from what the validator enforces.
 *
 * Run from the repo root with: pnpm ocpp:types
 * The output is committed; regenerate only if the schemas change.
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { compile, type JSONSchema } from 'json-schema-to-typescript';
import { V16_ACTIONS } from '../src/v16/actions.ts';
import { V16_SCHEMA_DIR } from '../src/v16/schema-files.ts';

const OUTPUT = new URL('../src/v16/types.generated.ts', import.meta.url);
const actions = Object.keys(V16_ACTIONS);

const parts = [
  '// Generated by packages/ocpp/scripts/generate-types.ts from the official OCPP 1.6 schemas.',
  '// Do not edit by hand: run `pnpm ocpp:types` instead.',
  '',
];

for (const action of actions) {
  for (const [file, typeName] of [
    [action, `${action}Request`],
    [`${action}Response`, `${action}Response`],
  ] as const) {
    const schema = JSON.parse(
      readFileSync(join(V16_SCHEMA_DIR, `${file}.json`), 'utf8'),
    ) as JSONSchema;
    // The schemas' titles already follow this naming; the explicit name makes it independent of that.
    parts.push(
      await compile({ ...schema, title: typeName }, typeName, {
        bannerComment: '',
        additionalProperties: false,
        declareExternallyReferenced: true,
        format: false,
      }),
    );
  }
}

parts.push(
  '/** Request payload for each OCPP 1.6 action. */',
  'export interface V16RequestMap {',
  ...actions.map((action) => `  ${action}: ${action}Request;`),
  '}',
  '',
  '/** Response payload for each OCPP 1.6 action. */',
  'export interface V16ResponseMap {',
  ...actions.map((action) => `  ${action}: ${action}Response;`),
  '}',
  '',
);

writeFileSync(OUTPUT, parts.join('\n'));
console.log(`Wrote ${actions.length * 2} payload types to ${OUTPUT.pathname}`);
